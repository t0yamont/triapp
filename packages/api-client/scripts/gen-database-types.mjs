// Generate the Supabase `Database` type from a live Postgres schema — WITHOUT Docker.
// `supabase gen types` needs a container; this introspects information_schema directly.
//
//   DATABASE_URL=postgresql://postgres@127.0.0.1:5432/postgres node scripts/gen-database-types.mjs > src/database.types.ts
//
// Run it against a local Postgres with the migrations applied, or against your linked
// project's db-url. Deterministic; commit the output.

import pg from 'pg';

const url = process.env.DATABASE_URL;
if (!url) {
  console.error('Set DATABASE_URL to a Postgres connection string.');
  process.exit(1);
}

const UDT_TO_TS = {
  uuid: 'string', text: 'string', varchar: 'string', bpchar: 'string', name: 'string',
  date: 'string', timestamptz: 'string', timestamp: 'string', time: 'string', timetz: 'string', bytea: 'string',
  int2: 'number', int4: 'number', int8: 'number', numeric: 'number', float4: 'number', float8: 'number',
  bool: 'boolean', json: 'Json', jsonb: 'Json',
  _int2: 'number[]', _int4: 'number[]', _int8: 'number[]', _numeric: 'number[]',
  _uuid: 'string[]', _text: 'string[]', _varchar: 'string[]',
};

function tsType(col) {
  if (col.data_type === 'USER-DEFINED') return `Database["public"]["Enums"]["${col.udt_name}"]`;
  return UDT_TO_TS[col.udt_name] ?? 'unknown';
}

const client = new pg.Client({ connectionString: url });
await client.connect();

const { rows: cols } = await client.query(`
  select c.table_name, c.column_name, c.is_nullable, c.column_default, c.data_type, c.udt_name
  from information_schema.columns c
  where c.table_schema = 'public'
    and c.table_name in (
      select table_name from information_schema.tables
      where table_schema = 'public' and table_type = 'BASE TABLE')
  order by c.table_name, c.ordinal_position`);

const { rows: enumRows } = await client.query(`
  select t.typname as enum_name, e.enumlabel as value
  from pg_type t
  join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public'
  order by t.typname, e.enumsortorder`);
await client.end();

const enums = {};
for (const r of enumRows) (enums[r.enum_name] ??= []).push(r.value);

const tables = {};
for (const c of cols) (tables[c.table_name] ??= []).push(c);

const emitRow = (list) =>
  list.map((c) => `          ${c.column_name}: ${tsType(c)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('\n');
const emitInsert = (list) =>
  list
    .map((c) => {
      const optional = c.is_nullable === 'YES' || c.column_default !== null;
      return `          ${c.column_name}${optional ? '?' : ''}: ${tsType(c)}${c.is_nullable === 'YES' ? ' | null' : ''}`;
    })
    .join('\n');
const emitUpdate = (list) =>
  list.map((c) => `          ${c.column_name}?: ${tsType(c)}${c.is_nullable === 'YES' ? ' | null' : ''}`).join('\n');

let out = `// GENERATED by scripts/gen-database-types.mjs from the applied migrations. Do not edit by hand.
// Regenerate: DATABASE_URL=... pnpm --filter @ironflow/api-client gen:types

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export interface Database {
  public: {
    Tables: {
`;

for (const name of Object.keys(tables).sort()) {
  const list = tables[name];
  out += `      ${name}: {
        Row: {
${emitRow(list)}
        };
        Insert: {
${emitInsert(list)}
        };
        Update: {
${emitUpdate(list)}
        };
        Relationships: [];
      };
`;
}

out += `    };
    Views: { [_ in never]: never };
    Functions: { [_ in never]: never };
    Enums: {
`;
for (const name of Object.keys(enums).sort()) {
  out += `      ${name}: ${enums[name].map((v) => `"${v}"`).join(' | ')};\n`;
}
out += `    };
    CompositeTypes: { [_ in never]: never };
  };
}
`;

process.stdout.write(out);
